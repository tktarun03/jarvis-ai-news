"""Orchestration: build one dated edition and update the archive, idempotently."""
from __future__ import annotations

from datetime import datetime, timedelta
from pathlib import Path

from . import select as sel
from .common import (domain_allowed, domain_of, iso, load_json, normalize_url, parse_iso, public_url,
                     save_json, story_id, title_fingerprint, truncate, tz, write_text)
from .covers import render_cover
from .feeds import Fetcher, FixtureFetcher, article_published, article_text, page_meta, parse_feed
from .images import find_publisher_image, publisher_image
from .render import render_edition
from .summarize import Summarizer

SCHEMA_VERSION = 1


class Skip(Exception):
    """Raised when there is nothing to publish (already published, or too few verified stories)."""


def edition_paths(root: Path, date: str) -> dict:
    return {
        "json": root / "data" / f"{date}.json",
        "html": root / "news" / f"{date}.html",
        "covers": root / "assets" / "images" / "covers" / date,
    }


def allowed_domains(sources: dict) -> set[str]:
    out = {domain_of(f["url"]) for f in sources["feeds"]}
    # Feed hosts differ from article hosts for a few publishers (feeds.bbci.co.uk -> bbc.com).
    out |= {".".join(d.split(".")[-2:]) for d in list(out)}
    out |= {"bbc.com", "bbc.co.uk", "livemint.com", "indiatimes.com"}
    out |= set(sources.get("extra_trusted_domains", []))
    return out


def _make_story(base: dict, region: str, cfg: dict, date: str, root: Path,
                image_url: str | None = None, fetcher=None) -> dict:
    sid = base["id"]
    cat = cfg["categories"][base["category"]]
    rel = f"assets/images/covers/{date}/{sid}.svg"
    write_text(root / rel, render_cover(sid, base["category"], cat["label"], cat["color"],
                                         base["source"]["domain"], date))
    generated = {"type": "generated", "src": rel, "alt": f"Abstract {cat['label'].lower()} cover for: {base['headline']}",
                 "credit": "Original cover generated by JARVIS", "fallback": rel}
    img_cfg = cfg["images"]
    pub = publisher_image(img_cfg["mode"], image_url, base, rel, root, date, fetcher, img_cfg["max_download_bytes"])
    base["image"] = pub or generated
    base["region"] = region
    return base


def refresh_images(root: Path, cfg: dict, sources: dict, date: str, fetcher=None) -> tuple[int, int]:
    """Re-check every story of an existing edition for a publisher image (e.g. after enabling images)."""
    fetcher = fetcher or Fetcher(cfg["verification"]["request_timeout_seconds"])
    path = edition_paths(root, date)["json"]
    ed = load_json(path)
    if not ed:
        raise Skip(f"no edition {date}")
    found = 0
    total = 0
    for region in ("global", "india"):
        for s in ed["stories"][region]:
            total += 1
            fallback = s["image"].get("fallback") or s["image"]["src"]
            resp = fetcher.get(s["source"]["url"], accept="text/html")
            url = find_publisher_image(resp.text, resp.url) if resp.status and 200 <= resp.status < 400 else None
            pub = publisher_image(cfg["images"]["mode"], url, s, fallback, root, date, fetcher, cfg["images"]["max_download_bytes"])
            if pub:
                s["image"] = pub
                found += 1
            elif s["image"]["type"] != "generated":
                cat = cfg["categories"][s["category"]]
                s["image"] = {"type": "generated", "src": fallback, "fallback": fallback,
                              "alt": f"Abstract {cat['label'].lower()} cover for: {s['headline']}",
                              "credit": "Original cover generated by JARVIS"}
    save_json(path, ed)
    rerender_all(root, cfg)
    return found, total


def _update_archive(root: Path, edition: dict) -> list[dict]:
    idx_path = root / "data" / "index.json"
    idx = load_json(idx_path, {"schema_version": SCHEMA_VERSION, "editions": []})
    entries = [e for e in idx["editions"] if e["date"] != edition["edition_date"]]
    top = (edition["stories"]["global"] or edition["stories"]["india"] or [{}])[0].get("headline")
    entries.append({
        "date": edition["edition_date"],
        "number": edition["edition_number"],
        "counts": {"global": len(edition["stories"]["global"]), "india": len(edition["stories"]["india"])},
        "top_headline": top,
        "html": f"news/{edition['edition_date']}.html",
        "json": f"data/{edition['edition_date']}.json",
        "generated_at": edition["generated_at"],
    })
    entries.sort(key=lambda e: e["date"], reverse=True)
    idx = {"schema_version": SCHEMA_VERSION, "latest": entries[0]["date"], "updated_at": edition["generated_at"], "editions": entries}
    save_json(idx_path, idx)
    return entries


def _clear_edition_covers(root: Path, date: str) -> None:
    for folder in (edition_paths(root, date)["covers"], root / "assets" / "images" / "news" / date):
        if folder.is_dir():
            for f in folder.iterdir():
                if f.is_file():
                    f.unlink()


def _update_seen(root: Path, edition: dict, keep_days: int, now: datetime) -> None:
    path = root / "data" / "seen.json"
    seen = load_json(path, {"urls": {}, "titles": {}})
    cutoff = (now - timedelta(days=keep_days)).date().isoformat()
    for kind in ("urls", "titles"):
        seen[kind] = {k: v for k, v in seen.get(kind, {}).items() if v >= cutoff and v != edition["edition_date"]}
    for s in edition["stories"]["global"] + edition["stories"]["india"]:
        seen["urls"][normalize_url(s["source"]["url"])] = edition["edition_date"]
        seen["titles"][title_fingerprint(s["source_title"])] = edition["edition_date"]
        for c in s.get("corroboration", []):
            seen["urls"][normalize_url(c["url"])] = edition["edition_date"]
    save_json(path, seen)


def _edition_number(root: Path, date: str) -> int:
    idx = load_json(root / "data" / "index.json", {"editions": []})
    existing = {e["date"]: e["number"] for e in idx["editions"]}
    if date in existing:
        return existing[date]
    return max(existing.values(), default=0) + 1


def write_outputs(root: Path, edition: dict, cfg: dict, now: datetime) -> None:
    zone = tz(cfg)
    date = edition["edition_date"]
    p = edition_paths(root, date)
    save_json(p["json"], edition)
    entries = _update_archive(root, edition)
    _update_seen(root, edition, cfg["edition"]["dedupe_memory_days"], now)
    write_text(p["html"], render_edition(edition, entries, cfg, zone, base="../"))
    latest = load_json(root / "data" / f"{entries[0]['date']}.json")
    write_text(root / "index.html", render_edition(latest, entries, cfg, zone, base=""))


def rerender_all(root: Path, cfg: dict) -> int:
    """Re-render every edition page from its JSON (after a template or CSS change)."""
    zone = tz(cfg)
    idx = load_json(root / "data" / "index.json", {"editions": []})
    entries = idx["editions"]
    for e in entries:
        ed = load_json(root / "data" / f"{e['date']}.json")
        write_text(root / "news" / f"{e['date']}.html", render_edition(ed, entries, cfg, zone, base="../"))
    if entries:
        write_text(root / "index.html", render_edition(load_json(root / "data" / f"{entries[0]['date']}.json"), entries, cfg, zone, base=""))
    return len(entries)


def run_daily(root: Path, cfg: dict, sources: dict, now: datetime, force: bool = False,
              fixtures: Path | None = None, log_fn=print) -> dict:
    zone = tz(cfg)
    date = now.astimezone(zone).date().isoformat()
    paths = edition_paths(root, date)
    if paths["json"].exists() and not force:
        raise Skip(f"edition {date} already published; use --force to rebuild it")

    ed_cfg, ver = cfg["edition"], cfg["verification"]
    fetcher = FixtureFetcher(fixtures) if fixtures else Fetcher(ver["request_timeout_seconds"])
    rejected: list[dict] = []
    feed_health = {"ok": [], "failed": []}
    items = []
    for src in sources["feeds"]:
        if isinstance(fetcher, FixtureFetcher):
            fetcher.register_feed(src["url"], src["id"])
        resp = fetcher.get(src["url"], accept="application/rss+xml, application/atom+xml, application/xml, text/xml")
        if resp.status != 200 or not resp.text:
            feed_health["failed"].append({"id": src["id"], "error": resp.error or f"HTTP {resp.status}"})
            continue
        try:
            parsed = parse_feed(resp.text, src)
            items.extend(parsed)
            feed_health["ok"].append({"id": src["id"], "items": len(parsed)})
        except Exception as exc:
            feed_health["failed"].append({"id": src["id"], "error": f"parse error {type(exc).__name__}"})
    log_fn(f"feeds ok={len(feed_health['ok'])} failed={len(feed_health['failed'])} items={len(items)}")

    seen = load_json(root / "data" / "seen.json", {"urls": {}, "titles": {}})
    # A forced rebuild of today must not treat today's own stories as duplicates.
    seen = {k: {u: d for u, d in v.items() if d != date} for k, v in seen.items()}
    if force:
        _clear_edition_covers(root, date)
    cands = sel.build_candidates(items, cfg, now, seen, sources.get("blocked_patterns", []), rejected)
    cands = sel.cluster(cands, ed_cfg["title_similarity_threshold"])
    cands = sel.rank(cands, now, ed_cfg["lookback_hours"])
    log_fn(f"candidates after window/dedupe/cluster: {len(cands)}")

    allowed = allowed_domains(sources)
    summarizer = Summarizer(cfg, rejected)
    valid_cats = set(cfg["categories"])
    out = {"global": [], "india": []}
    limits = {"global": ed_cfg["max_global"], "india": ed_cfg["max_india"]}
    per_source: dict[str, int] = {}

    for c in cands:
        region = c.region
        if len(out[region]) >= limits[region]:
            continue
        sid_src = c.item.source["id"]
        if per_source.get(sid_src, 0) >= ed_cfg["max_per_source"]:
            continue
        url = public_url(c.item.url)
        dom = domain_of(url)
        if not url.startswith("https://"):
            rejected.append({"title": c.item.title, "url": url, "reason": "not https"}); continue
        if not domain_allowed(dom, allowed):
            rejected.append({"title": c.item.title, "url": url, "reason": f"domain {dom} not on trusted list"}); continue

        checks, date_source, body = [], "feed", ""
        status, image_url = None, None
        if ver["check_links"]:
            resp = fetcher.get(url, accept="text/html")
            status = resp.status
            if resp.status and 200 <= resp.status < 400:
                checks.append("link resolves")
                pub = article_published(resp.text)
                if pub:
                    drift = abs((pub - c.item.published).total_seconds()) / 3600
                    if drift > ver["max_feed_vs_article_date_drift_hours"]:
                        rejected.append({"title": c.item.title, "url": url,
                                         "reason": f"article date {iso(pub)} disagrees with feed date (stale or republished)"})
                        continue
                    date_source = "article"
                    checks.append("publication date confirmed on article page")
                body = article_text(resp.text, cfg["summarizer"]["max_source_chars"])
                image_url = find_publisher_image(resp.text, resp.url)
                meta = page_meta(resp.text)
                if not c.item.description and meta.get("og:description"):
                    c.item.description = meta["og:description"]
            elif resp.status in (401, 403, 429) and c.item.source["trust"] >= ver["accept_blocked_status_for_trust_at_least"]:
                checks.append(f"publisher blocks automated readers (HTTP {resp.status}); trusted feed accepted")
            else:
                rejected.append({"title": c.item.title, "url": url, "reason": f"link check failed ({resp.error or resp.status})"})
                continue

        fallback_cat = sel.categorize(f"{c.item.title} {c.item.description}", region, valid_cats)
        summ = summarizer.summarize(c.item.title, c.item.source["name"], c.item.description, body, fallback_cat)
        if summ.get("rejected"):
            rejected.append({"title": c.item.title, "url": url, "reason": summ["rejected"]}); continue
        checks.append("summary grounded in publisher text" if summ["summary_mode"] == "ai-grounded"
                      else "publisher's own summary used (no AI summary)")

        story = {
            "id": story_id(url),
            "rank": len(out[region]) + 1,
            "headline": summ["headline"],
            "source_title": c.item.title,
            "summary": summ["summary"],
            "key_insights": summ["key_insights"],
            "impact": summ["impact"],
            "category": summ["category"],
            "tags": summ["tags"],
            "source": {"name": c.item.source["name"], "domain": dom, "url": url, "feed": c.item.source["id"],
                       "trust": c.item.source["trust"]},
            "published_at": iso(c.item.published),
            "published_precision": "time",
            "corroboration": [{"name": x.source["name"], "url": public_url(x.url)} for x in c.cluster[1:]][:4],
            "summary_mode": summ["summary_mode"],
            "verification": {"link_status": status, "date_source": date_source, "checks": checks},
            "score": round(c.score, 1),
        }
        out[region].append(_make_story(story, region, cfg, date, root, image_url, fetcher))
        per_source[sid_src] = per_source.get(sid_src, 0) + 1

    total = len(out["global"]) + len(out["india"])
    if total < ed_cfg["min_stories_to_publish"]:
        raise Skip(f"only {total} stories passed verification (minimum {ed_cfg['min_stories_to_publish']}); "
                   f"keeping the previous edition live. Failed feeds: {len(feed_health['failed'])}")

    edition = {
        "schema_version": SCHEMA_VERSION,
        "edition_date": date,
        "edition_number": _edition_number(root, date),
        "edition_type": "daily",
        "timezone": cfg["schedule"]["timezone"],
        "generated_at": iso(now),
        "window": {"start": iso(now - timedelta(hours=ed_cfg["lookback_hours"])), "end": iso(now)},
        "publisher": {"name": cfg["site"]["publisher"], "signature": cfg["site"]["signature"],
                      "agent_credit": cfg["site"]["agent_credit"]},
        "summarizer": {"enabled": summarizer.enabled, "model": summarizer.model if summarizer.enabled else None},
        "counts": {"global": len(out["global"]), "india": len(out["india"])},
        "stories": out,
        "rejected": rejected[:80],
        "feeds": feed_health,
    }
    write_outputs(root, edition, cfg, now)
    return edition


def build_from_curated(root: Path, cfg: dict, sources: dict, curated_path: Path, now: datetime, force: bool = False) -> dict:
    """Render a hand-verified edition (the launch sample) through the same cover/JSON/HTML/archive path."""
    cur = load_json(curated_path)
    date = cur["edition_date"]
    if edition_paths(root, date)["json"].exists() and not force:
        raise Skip(f"edition {date} already published; use --force to rebuild it")
    _clear_edition_covers(root, date)
    allowed = allowed_domains(sources)
    out = {"global": [], "india": []}
    seen_ids = set()
    for region in ("global", "india"):
        for n, s in enumerate(cur["stories"][region], start=1):
            url = public_url(s["url"])
            dom = domain_of(url)
            if not domain_allowed(dom, allowed):
                raise ValueError(f"curated story domain {dom} is not on the trusted list")
            sid = story_id(url)
            if sid in seen_ids:
                raise ValueError(f"duplicate curated story {url}")
            seen_ids.add(sid)
            story = {
                "id": sid, "rank": n,
                "headline": truncate(s["headline"], 110), "source_title": s["source_title"],
                "summary": s["summary"], "key_insights": s["key_insights"], "impact": s.get("impact"),
                "category": s["category"], "tags": s.get("tags", []),
                "source": {"name": s["source_name"], "domain": dom, "url": url, "feed": None, "trust": s.get("trust", 2)},
                "published_at": s["published_at"],
                "published_precision": s.get("published_precision", "time"),
                "corroboration": s.get("corroboration", []),
                "summary_mode": "editor-verified",
                "verification": {"link_status": None, "date_source": "editor", "checks": s["checks"]},
                "score": None,
            }
            out[region].append(_make_story(story, region, cfg, date, root, s.get("image_url"), Fetcher()))
    edition = {
        "schema_version": SCHEMA_VERSION,
        "edition_date": date,
        "edition_number": _edition_number(root, date),
        "edition_type": "launch-sample",
        "timezone": cfg["schedule"]["timezone"],
        "generated_at": iso(now),
        "window": cur["window"],
        "publisher": {"name": cfg["site"]["publisher"], "signature": cfg["site"]["signature"],
                      "agent_credit": cfg["site"]["agent_credit"]},
        "summarizer": {"enabled": False, "model": None},
        "counts": {"global": len(out["global"]), "india": len(out["india"])},
        "stories": out,
        "rejected": cur.get("rejected", []),
        "feeds": {"ok": [], "failed": [], "note": "hand-curated launch edition"},
    }
    write_outputs(root, edition, cfg, now)
    return edition
